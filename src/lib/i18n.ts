export function useTranslation() {
  const [lang, setLang] = useState<LanguageCode>('en');

  useEffect(() => {
    const handleLangChange = () => {
      const saved = loadFromStore<LanguageCode>(STORAGE_KEYS.language);
      if (saved && ['en', 'hi', 'mr', 'bn', 'ta', 'te', 'gu', 'kn', 'ml'].includes(saved)) {
        setLang(saved);
      }
    };
    
    if (typeof window !== 'undefined') {
      handleLangChange();
      window.addEventListener('language-changed', handleLangChange);
      return () => window.removeEventListener('language-changed', handleLangChange);
    }
  }, []);

  const t = (key: string): string => {
    const currentLangTranslations = translations[lang] || translations['en'];
    return currentLangTranslations[key] || translations['en'][key] || key;
  };

  return { t, lang };
}